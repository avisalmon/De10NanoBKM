#!/usr/bin/env python
"""Stop a commit that would publish a secret, a personal file, or a pile of build outputs.

    python scripts/check_staged_secrets.py          # checks what is staged right now
    pre-commit install                              # runs it automatically before every commit

Pure Python, nothing to download: a hook that needs a Go toolchain or a download can fail on a
newcomer's machine and block every commit. CI still runs gitleaks over the full history as a
second, independent net.

Blocks: key-shaped strings (see secret_patterns.py), files that should never be public (.env
files, private keys, tool licence files tied to one computer), Quartus build-output folders,
bitstreams, and files too big for git. Exit code 1 = blocked.
"""

import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from secret_patterns import PATTERNS  # noqa: E402

MAX_BYTES = 50 * 1024 * 1024  # GitHub refuses files over 100 MB and warns from 50 MB

FORBIDDEN_NAMES = [
    (
        re.compile(r"(^|/)\.env($|\.(?!example$))"),
        "an environment file (secrets live in .env, never in git)",
    ),
    (re.compile(r"\.(pem|p12|pfx|key)$"), "a private key or certificate"),
    (re.compile(r"(^|/)id_(rsa|ed25519|ecdsa)(\.pub)?$"), "an SSH key"),
    (re.compile(r"(^|/)env/"), "the virtualenv folder"),
    (
        re.compile(r"(^|/)[^/]*licen[cs]e[^/]*\.dat$", re.I),
        "a tool licence file (it is tied to one computer's network card: personal)",
    ),
    (
        re.compile(r"(^|/)(db|incremental_db|output_files|qdb|sim_build)/"),
        "a build-output folder (regenerated by every compile; publish bitstreams as a Release)",
    ),
    (
        re.compile(r"\.(sof|pof|jic|rbf)$", re.I),
        "a bitstream (rebuilt by every compile; share it as a GitHub Release)",
    ),
]
SELF_EXEMPT = {"scripts/secret_patterns.py", "scripts/check_staged_secrets.py"}


def check_files(files: dict[str, bytes]) -> list[str]:
    """`files` maps staged path -> staged content. Returns one message per problem."""
    problems = []
    for path, content in sorted(files.items()):
        for pattern, why in FORBIDDEN_NAMES:
            if pattern.search(path):
                problems.append(f"{path}: this is {why}")
        if len(content) > MAX_BYTES:
            size = len(content) // (1024 * 1024)
            problems.append(f"{path}: {size} MB is too big for git (attach it to a GitHub Release)")
        if path in SELF_EXEMPT or b"\0" in content[:4096]:
            continue
        text = content.decode("utf-8", errors="ignore")
        for label, pattern in PATTERNS.items():
            if pattern.search(text):
                problems.append(f"{path}: contains something shaped like a {label}")
    return problems


def staged_files() -> dict[str, bytes]:
    names = subprocess.run(
        ["git", "diff", "--cached", "--name-only", "--diff-filter=ACM", "-z"],
        capture_output=True,
    ).stdout.decode("utf-8", errors="ignore")
    files = {}
    for name in filter(None, names.split("\0")):
        blob = subprocess.run(["git", "show", f":{name}"], capture_output=True)
        files[name] = blob.stdout if blob.returncode == 0 else b""
    return files


def main() -> int:
    problems = check_files(staged_files())
    if not problems:
        return 0
    print("Commit blocked: this commit would publish something it should not.\n")
    for problem in problems:
        print(f"  - {problem}")
    print(
        "\nUnstage it (git restore --staged <file>). If a real key was involved, rotate it.\n"
        "See the publish-to-github skill, section 4 (pre-push check)."
    )
    return 1


if __name__ == "__main__":
    sys.exit(main())
