#!/usr/bin/env python
"""Keep the Claude Code and GitHub Copilot copies of the repo's skills identical.

    python scripts/sync_skills.py            # write the copies
    python scripts/sync_skills.py --check    # exit 1 if they have drifted (CI and tests use this)

Source of truth: `.claude/skills/<name>/SKILL.md` (edit THESE). Generated, never edit by hand:
  .github/skills/<name>/...          GitHub Copilot's copy of every skill (same SKILL.md format)
  .github/copilot-instructions.md    Copilot's repo instructions: CLAUDE.md + a skills index
  AGENTS.md                          same content, for any other agent that reads AGENTS.md

The index lists each skill's trigger phrases and path, so a tool that does not auto-discover
skills can still be told: "when the owner says X, open that SKILL.md and follow it".

It also stamps the "Last updated" mark on README.md from the newest date in docs/lessons_log.md,
between `last-updated` markers. A hand-written date goes stale the first time someone adds a
lesson and forgets; this one is computed, and `--check` fails while it is behind.
"""

import argparse
import re
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / ".claude" / "skills"
COPY = ROOT / ".github" / "skills"
INSTRUCTION_FILES = [ROOT / ".github" / "copilot-instructions.md", ROOT / "AGENTS.md"]
LESSONS = ROOT / "docs" / "lessons_log.md"
MARKED_FILES = {ROOT / "README.md": "md"}
MARK = re.compile(r"(<!-- last-updated:start -->)(.*?)(<!-- last-updated:end -->)", re.S)

HEADER = """<!--
GENERATED by scripts/sync_skills.py from CLAUDE.md and .claude/skills/. Do not edit by hand:
edit CLAUDE.md or a skill under .claude/skills/, then run `python scripts/sync_skills.py`.
-->

> These instructions are for any AI coding assistant (GitHub Copilot, Claude Code, others).
> Where they say "Claude", read "you". The skills are playbooks: **when the owner's words match
> a skill's triggers, open that skill's `SKILL.md` and follow it.** The same skills live in
> `.claude/skills/` (Claude Code) and `.github/skills/` (GitHub Copilot); they are identical.

"""


def parse_frontmatter(text: str) -> dict:
    match = re.match(r"^---\r?\n(.*?)\r?\n---", text, flags=re.S)
    if not match:
        raise ValueError("SKILL.md has no frontmatter")
    block = match.group(1)
    name = re.search(r"^name:\s*(\S+)\s*$", block, flags=re.M)
    desc = re.search(r"^description:\s*>?\s*\r?\n?(.*)$", block, flags=re.S | re.M)
    if not name or not desc:
        raise ValueError("frontmatter needs name and description")
    description = " ".join(line.strip() for line in desc.group(1).splitlines() if line.strip())
    return {"name": name.group(1), "description": description}


def skills() -> list[dict]:
    found = []
    for path in sorted(SOURCE.glob("*/SKILL.md")):
        meta = parse_frontmatter(path.read_text(encoding="utf-8"))
        meta["dir"] = path.parent.name
        found.append(meta)
    return found


def summary(description: str) -> tuple[str, str]:
    """Split a description into (what it does, trigger phrases)."""
    head, _, triggers = description.partition("TRIGGER:")
    return head.strip(), triggers.strip()


def index_table() -> str:
    rows = [
        "## Skills index",
        "",
        "| Skill | What it does | Say things like | File |",
        "|---|---|---|---|",
    ]
    for meta in skills():
        what, triggers = summary(meta["description"])
        what = what.replace("|", "/")
        rows.append(
            f"| `{meta['name']}` | {what} | {triggers.replace('|', '/')} | "
            f"`.github/skills/{meta['dir']}/SKILL.md` |"
        )
    return "\n".join(rows) + "\n"


LINK = re.compile(r"\]\((?!https?:|mailto:|#|\.\./)([^)\s]+)\)")


def instructions_text(link_prefix: str = "") -> str:
    """CLAUDE.md + the skills index. `link_prefix` fixes relative links for a file that lives
    in a subfolder (the .github copy needs `../docs/...`; AGENTS.md at the root needs nothing)."""
    body = (ROOT / "CLAUDE.md").read_text(encoding="utf-8")
    body = body.replace(
        "# Instructions for Claude working in this repo",
        "# Instructions for the AI assistant working in this repo",
        1,
    )
    body = body.replace(
        "`.claude/skills/` (your playbooks)",
        "`.github/skills/` and `.claude/skills/` (your playbooks, identical copies)",
    )
    if link_prefix:
        body = LINK.sub(lambda m: f"]({link_prefix}{m.group(1)})", body)
    return HEADER + body.rstrip() + "\n\n" + index_table()


def latest_lessons() -> tuple[str, int]:
    """("20 October 2026", 5): the newest date in the lessons log and how many lessons it added.

    Written out in full, never 20/10, because the people reading this are in several countries
    and half of them read 10/20.
    """
    from datetime import date

    text = LESSONS.read_text(encoding="utf-8")
    match = re.search(r"^## (\d{4})-(\d{2})-(\d{2})\s*$", text, re.M)
    if not match:
        return "", 0
    day = date(int(match[1]), int(match[2]), int(match[3]))
    section = text[match.end() :]
    following = re.search(r"^## ", section, re.M)
    if following:
        section = section[: following.start()]
    count = len(re.findall(r"^- \*\*", section, re.M))
    return f"{day.day} {day.strftime('%B %Y')}", count


def mark_text(kind: str) -> str:
    when, count = latest_lessons()
    if not when:
        return ""
    lessons = f"{count} new lesson{'s' if count != 1 else ''}"
    return f"\n**Last updated {when}** · {lessons} · [See what's new](docs/lessons_log.md)\n"


def stamped(path: Path, kind: str) -> bytes:
    """The file as it should be: unchanged except inside its `last-updated` markers."""
    text = path.read_bytes().decode("utf-8")
    if not MARK.search(text):
        raise SystemExit(f"{path.relative_to(ROOT)} has no last-updated markers")
    body = mark_text(kind)
    if "\r\n" in text:
        body = body.replace("\n", "\r\n")
    return MARK.sub(lambda m: m[1] + body + m[3], text, count=1).encode("utf-8")


def expected_files() -> dict[Path, bytes]:
    """Every file that must exist in the generated places, with its exact content."""
    out: dict[Path, bytes] = {}
    for path, kind in MARKED_FILES.items():
        out[path] = stamped(path, kind)
    for src in SOURCE.rglob("*"):
        if src.is_file():
            out[COPY / src.relative_to(SOURCE)] = src.read_bytes()
    for target in INSTRUCTION_FILES:
        prefix = "../" if target.parent != ROOT else ""
        out[target] = instructions_text(prefix).encode("utf-8")
    return out


def normalise(data: bytes) -> bytes:
    """Line endings are not content: a Windows checkout may use CRLF."""
    return data.replace(b"\r\n", b"\n")


def drift() -> list[str]:
    problems = []
    expected = expected_files()
    for path, content in expected.items():
        if not path.exists():
            problems.append(f"missing: {path.relative_to(ROOT)}")
        elif normalise(path.read_bytes()) != normalise(content):
            problems.append(f"out of date: {path.relative_to(ROOT)}")
    if COPY.exists():
        for path in COPY.rglob("*"):
            if path.is_file() and path not in expected:
                problems.append(f"stale (no longer in .claude/skills): {path.relative_to(ROOT)}")
    return problems


def write() -> list[str]:
    changed = []
    expected = expected_files()
    if COPY.exists():
        for path in list(COPY.rglob("*")):
            if path.is_file() and path not in expected:
                path.unlink()
                changed.append(f"removed {path.relative_to(ROOT)}")
        for folder in sorted((p for p in COPY.rglob("*") if p.is_dir()), reverse=True):
            if not any(folder.iterdir()):
                shutil.rmtree(folder)
    for path, content in expected.items():
        if not path.exists() or normalise(path.read_bytes()) != normalise(content):
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content)
            changed.append(f"wrote {path.relative_to(ROOT)}")
    return changed


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the copies have drifted")
    args = parser.parse_args(argv)
    if args.check:
        problems = drift()
        for problem in problems:
            print(problem)
        if problems:
            print("Run: python scripts/sync_skills.py")
            return 1
        print(f"in sync: {len(skills())} skills, {len(INSTRUCTION_FILES)} instruction files")
        return 0
    changed = write()
    print("\n".join(changed) if changed else "already in sync")
    return 0


if __name__ == "__main__":
    sys.exit(main())
